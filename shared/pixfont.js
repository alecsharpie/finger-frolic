// Fill colours: each a ramp, light at the top of the letters and shade at the foot.
export const INKS = {
  white: ['#ffffff', '#f4efff', '#cfc4f0', '#9e90cc'],
  gold: ['#fff6c0', '#ffd23f', '#f0a020', '#b86a10'],
  red: ['#ffd0d6', '#ff6b7f', '#e0304a', '#9a1830'],
  ice: ['#ffffff', '#bfe8ff', '#7cc4e8', '#3b6f9a'],
  green: ['#e0ffd0', '#7fe36b', '#3fa34d', '#21663a'],
  violet: ['#f4e8ff', '#c69cff', '#8a4dff', '#5420b0'],
  flame: ['#fff3a0', '#ffb02e', '#ff5a3c', '#a8242c'],
};
export const inkFor = c => INKS[c] || ramp(c);

function glyphs(str) { return [...String(str).toUpperCase()].map(ch => G[ch]).filter(Boolean); }

export function measure(str) { const g = glyphs(str); return g.reduce((w, r) => w + r[0].length + 1, 0) - (g.length ? 1 : 0); }

const CACHE = new Map();
// A baked line of text: width = letters + 1-px gaps + outline, height 7 + outline + shadow.
export function textCanvas(str, color = 'white') {
  const key = str + '|' + color;
  let c = CACHE.get(key);
  if (c) return c;
  const gl = glyphs(str), w = Math.max(1, measure(str)) + 2, h = 7 + 3;
  const P = new Painter(w, h, { f: inkFor(color), sh: flat('#140b26') }, '#140b26');
  let x = 1;
  for (const g of gl) {
    for (let y = 0; y < 7; y++) for (let k = 0; k < g[y].length; k++) if (g[y][k] === '1') P.px(x + k, y + 1, 'f', y < 2 ? 0 : y < 5 ? 1 : 2);
    x += g[0].length + 1;
  }
  P.outline();
  // a hard drop shadow one pixel down
  for (let y = h - 2; y >= 0; y--) for (let xx = 0; xx < w; xx++) if (P.get(xx, y) != null && P.get(xx, y + 1) == null) P.px(xx, y + 1, 'sh', 1);
  c = P.bake();
  CACHE.set(key, c);
  return c;
}

// Draw text centred (or left-aligned) at (x, y = vertical middle) at an integer scale.
export function drawText(ctx, str, x, y, { color = 'white', scale = 1, align = 'center', alpha = 1 } = {}) {
  const c = textCanvas(str, color), w = c.width * scale, h = c.height * scale;
  const X = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x), Y = Math.round(y - h / 2);
  if (alpha !== 1) ctx.globalAlpha = alpha;
  ctx.drawImage(c, X, Y, w, h);
  if (alpha !== 1) ctx.globalAlpha = 1;
}
